import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { verifyStatefulAlerts } from './stateful-triage.mjs';
import { evidence, save, manifest } from './evidence.mjs';
process.loadEnvFile(process.env.STAGING_ENV_FILE ?? '.env.staging');
const origin = process.env.APP_ORIGIN;
const health = await fetch(new URL('/api/health', origin)).then(r => r.json());
if (health.environment !== 'staging') throw new Error('Staging required');
const file = process.argv[2];
if (!file) throw new Error('Pass the original redacted alerts.json report');
const raw = readFileSync(file);
const alerts = JSON.parse(raw).alerts;
const login = await fetch(new URL('/api/autenticacion/login', origin), { method: 'POST', headers: { Origin: origin, 'Content-Type': 'application/json' }, body: JSON.stringify({ cedula: '900000001', password: process.env.E2E_ADMIN_PASSWORD }) });
if (!login.ok) throw new Error('Authentication failed');
const cookies = login.headers.getSetCookie().map(value => value.split(';')[0]).join('; ');
const result = await verifyStatefulAlerts(origin, cookies, alerts);
const dir = evidence('dast-triage');
save(dir, 'verification.json', result);
const passed = result.probes.length > 0 && result.probes.every(proof => proof.passed);
manifest(dir, { status: passed ? 'PASS' : 'FAIL', originalReportSha256: createHash('sha256').update(raw).digest('hex'), origin, note: 'Reproduction evidence only; original scan status remains unchanged' });
console.log(JSON.stringify({ directory: dir, passed, probes: result.probes.length, classifiedAlerts: result.acceptedAlertIds.length }));
process.exitCode = passed ? 0 : 1;
